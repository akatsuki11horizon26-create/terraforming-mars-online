// Bundles the generated per-card SVGs into a single module the UI can inline.
// The art is machine-generated, so this is also the gate that enforces what is
// allowed into the page: anything that could execute or phone home is rejected
// here rather than trusted at render time.
//
// Usage: node scripts/build-card-art.mjs <source-dir>
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const sourceDir = process.argv[2];
if (!sourceDir) {
  console.error("usage: node scripts/build-card-art.mjs <source-dir>");
  process.exit(1);
}

const FORBIDDEN = [
  [/<script/i, "script element"],
  [/\son\w+\s*=/i, "inline event handler"],
  [/href\s*=\s*["']?\s*(?!#)/i, "external reference"],
  [/<image\b/i, "raster image element"],
  [/url\(\s*["']?(?!#)/i, "external url()"],
  [/@font-face/i, "font import"],
  [/<foreignObject/i, "foreignObject"],
  [/javascript:/i, "javascript: uri"],
  [/<!ENTITY/i, "xml entity"]
];

const MAX_BYTES = 8192;

const files = readdirSync(sourceDir).filter(name => name.endsWith(".svg"));
if (files.length === 0) {
  console.error(`no .svg files in ${sourceDir}`);
  process.exit(1);
}

const entries = [];
const rejected = [];
const seenIds = new Map();

for (const file of files.sort()) {
  const id = file.replace(/\.svg$/, "");
  const raw = readFileSync(join(sourceDir, file), "utf8");

  const problems = [];
  for (const [pattern, label] of FORBIDDEN) {
    if (pattern.test(raw)) problems.push(label);
  }
  if (Buffer.byteLength(raw) > MAX_BYTES) problems.push(`over ${MAX_BYTES} bytes`);
  if (!/^\s*(<\?xml[^>]*\?>\s*)?<svg\b/.test(raw)) problems.push("does not start with <svg>");
  if (!/viewBox\s*=\s*["']0 0 160 90["']/.test(raw)) problems.push("wrong or missing viewBox");
  if (/<text\b/i.test(raw)) problems.push("contains text element");

  // Inlined SVGs share one document, so a gradient id reused across two cards
  // would make one card silently adopt the other's fill.
  for (const match of raw.matchAll(/\sid\s*=\s*["']([^"']+)["']/g)) {
    const owner = seenIds.get(match[1]);
    if (owner && owner !== id) problems.push(`duplicate id "${match[1]}" (also in ${owner})`);
    seenIds.set(match[1], id);
  }

  if (problems.length > 0) {
    rejected.push({ file, problems });
    continue;
  }

  // "meet" keeps the whole drawing visible. The band is sized to the same 16:9
  // the artwork uses, so this fills it exactly without letterboxing, and a
  // rounding error shows a hairline of card background rather than slicing the
  // top and bottom off every illustration.
  const cleaned = raw
    .replace(/<\?xml[^>]*\?>/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+/g, " ")
    .replace(/\spreserveAspectRatio\s*=\s*["'][^"']*["']/g, "")
    .replace(/<svg\b/, '<svg preserveAspectRatio="xMidYMid meet"')
    .trim();

  entries.push([id, cleaned]);
}

const body = entries.map(([id, svg]) => `  ${JSON.stringify(id)}: ${JSON.stringify(svg)}`).join(",\n");
const out = `// Generated by scripts/build-card-art.mjs. Do not edit by hand.\nexport const CARD_ART = {\n${body}\n};\n`;
writeFileSync("app/card-art.data.js", out);
// Lookups are by arbitrary card id, so the map needs an index signature the
// generated object literal would not otherwise have.
writeFileSync("app/card-art.data.d.ts", "export declare const CARD_ART: Record<string, string | undefined>;\n");

console.log(`wrote app/card-art.data.js — ${entries.length} accepted, ${rejected.length} rejected`);
for (const { file, problems } of rejected) {
  console.log(`  REJECTED ${file}: ${problems.join(", ")}`);
}
if (rejected.length > 0) process.exitCode = 1;
