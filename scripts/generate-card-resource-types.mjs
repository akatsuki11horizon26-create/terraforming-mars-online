// Extracts each card's resourceType from the reference implementation and maps it
// onto our catalog ids by card name. The catalog generator never captured this
// field, so "add a Microbe to any card" had no way to tell which cards are legal
// targets.
//
// Usage: node scripts/generate-card-resource-types.mjs
// Reference path comes from TM_REFERENCE, defaulting to the same location the
// card catalog generator uses.
import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";

const REFERENCE =
  process.env.TM_REFERENCE ?? "C:\\Users\\takkun\\AppData\\Local\\Temp\\tm-reference";
const CARDS_ROOT = join(REFERENCE, "src", "server", "cards");

async function walk(dir) {
  const out = [];
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (entry.name.endsWith(".ts")) out.push(full);
  }
  return out;
}

const files = await walk(CARDS_ROOT);
if (files.length === 0) {
  console.error(`No card sources found under ${CARDS_ROOT}. Set TM_REFERENCE.`);
  process.exit(1);
}

// CardResource.MICROBE -> "microbe"
const toResource = symbol =>
  symbol
    .toLowerCase()
    .split("_")
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");

const byName = new Map();
for (const file of files) {
  const source = await readFile(file, "utf8");
  const resourceMatch = source.match(/resourceType:\s*CardResource\.([A-Z_]+)/);
  if (!resourceMatch) continue;

  // name: CardName.ANTS -> look up the string in CardName, but the literal card
  // name is also present in the CardName enum file; matching on the enum key is
  // enough because our catalog stores the printed name.
  const nameMatch = source.match(/name:\s*CardName\.([A-Z0-9_]+)/);
  if (!nameMatch) continue;

  byName.set(nameMatch[1], toResource(resourceMatch[1]));
}

const cardNameSource = await readFile(
  join(REFERENCE, "src", "common", "cards", "CardName.ts"),
  "utf8"
);
const enumToPrinted = new Map();
for (const line of cardNameSource.split("\n")) {
  const match = line.match(/^\s*([A-Z0-9_]+)\s*[:=]\s*'(.+?)'/);
  if (match) enumToPrinted.set(match[1], match[2]);
}

const { FULL_PROJECTS, FULL_CORPORATIONS, FULL_PRELUDES } = await import(
  pathToUrl(resolve(process.cwd(), "app", "full-card-catalog.js"))
);
const catalog = [...FULL_PROJECTS, ...FULL_CORPORATIONS, ...FULL_PRELUDES];
const catalogByName = new Map(catalog.map(card => [card.name, card.id]));

const entries = [];
const unmatched = [];
for (const [enumKey, resource] of byName) {
  const printed = enumToPrinted.get(enumKey);
  const id = printed ? catalogByName.get(printed) : undefined;
  if (!id) {
    unmatched.push(printed ?? enumKey);
    continue;
  }
  entries.push([id, resource]);
}
entries.sort((a, b) => a[0].localeCompare(b[0]));

const body = entries.map(([id, resource]) => `  ${JSON.stringify(id)}: ${JSON.stringify(resource)}`).join(",\n");
const out = `// GENERATED by scripts/generate-card-resource-types.mjs — do not edit by hand.
// Maps catalog card ids to the resource they hold, extracted from the reference
// implementation's resourceType declarations. ${entries.length} cards.

export const CARD_RESOURCE_TYPES = {
${body}
};

export function getCardResourceType(cardId) {
  return CARD_RESOURCE_TYPES[cardId];
}
`;

await writeFile(resolve(process.cwd(), "app", "card-resource-types.js"), out, "utf8");
console.log(`Wrote ${entries.length} resource-holding cards.`);
if (unmatched.length) {
  console.log(`Unmatched (not in our catalog, expected for unofficial modules): ${unmatched.length}`);
  console.log(unmatched.slice(0, 12).join(", "));
}

function pathToUrl(p) {
  return new URL(`file:///${p.replace(/\\/g, "/")}`).href;
}
